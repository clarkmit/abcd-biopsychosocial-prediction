# Deduplicate, override, and build flat lists: both timepoints

_spectra = {0: _obj_sub_t0, 2: _obj_sub_t2}
logger.info("=" * 70)


def run() -> None:
    """Run this stage (notebook cell 3)."""
    _missing = [r for r in _required if r not in ctx]
    if _missing:
        raise RuntimeError(
            f"The variable registry and circularity exclusions must be loaded before the spectrum ontology.\n"
            f"Missing: {_missing}"
        )

    for _tp, _spectrum in _spectra.items():
        # Deduplicate within each category
        for _cat in _spectrum:
            _seen = set()
            _deduped = []
            for _v in _spectrum[_cat]:
                if _v not in _seen:
                    _seen.add(_v)
                    _deduped.append(_v)
            if len(_deduped) < len(_spectrum[_cat]):
                logger.info(f"  Warning: T{_tp} Deduplicated '{_cat}': {len(_spectrum[_cat])} → {len(_deduped)}")
            _spectrum[_cat] = _deduped

        # Override within-category structure
        ctx.child_variables_for_each_time_point[_tp] = _spectrum
        if _tp in ctx.parent_variables_for_each_time_point:
            ctx.parent_variables_for_each_time_point[_tp] = {}

        # Build flat variable list
        _all_vars = []
        _seen_flat = set()
        for _vars in _spectrum.values():
            for _v in _vars:
                if _v not in _seen_flat:
                    _seen_flat.add(_v)
                    _all_vars.append(_v)

        if _tp == 0:
            ctx.t0_variables = _all_vars
        elif _tp == 2:
            ctx.t2_variables = _all_vars

    # Refresh the alias used by preprocessing
    ctx.variables_for_each_time_point = ctx.child_variables_for_each_time_point

    # Summary
    for _tp, _spectrum in _spectra.items():
        _flat = ctx.t0_variables if _tp == 0 else ctx.t2_variables
        logger.info("=" * 70)
        logger.info(f"FE: Obj/Sub Spectrum -- T{_tp} Within-Category Structure Loaded")
        logger.info("=" * 70)
        _total = 0
        for _cat, _vars in _spectrum.items():
            logger.info(f"  {_cat:<60s} {len(_vars):>4d} features")
            _total += len(_vars)
        logger.info(f"  {'-' * 60} {'-' * 4}")
        logger.info(f"  {'TOTAL (unique across categories)':<60s} {len(_flat):>4d} features")
        logger.info(f"  {'TOTAL (with cross-category overlap)':<60s} {_total:>4d} entries")
        logger.info(f"  t{_tp}_variables (flat): {len(_flat)}")
        logger.info("")

    logger.info(f"Timepoints available: {sorted(ctx.child_variables_for_each_time_point.keys())}")
