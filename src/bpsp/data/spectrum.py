"""Objective/subjective gradient: an alternative T0 and T2 within-category ontology (Fig 4).

Used only when `setup.objective_subjective_spectrum` is on. It arranges the
T0 and T2 within-category structure along an objective-to-subjective
continuum, to address the predictive discrepancy between objective
biophysical measures and parent-rated psychopathology/personality for
psychiatric outcomes. Seven measurement levels, plus a cross-domain set:

Objective No-Report   : cognitive tasks, neuroimaging PCs, genetic PCs,
                        Fitbit/physiological, physical measurements
Objective Rated       : SES, residential (T2 adds grades and diet)
Child-Self Measures   : school, family, social (child report)
Parent-to-Child       : CBCL psychopathology, personality, social
Child & Parent        : adverse life events (joint ratings)
Parent-Self (Psych)   : ASR psychopathology, personality, social
Parent-Self (Family)  : family style/dynamics, drug use
Inter                 : cross-domain set (demographics and summary
                        scores from several levels)

When on, it replaces child_variables_for_each_time_point[0] and [2],
variables_for_each_time_point, t0_variables and t2_variables after the
registry and circularity setup. Circularity exclusions, outcome variables
and helper functions are unchanged.

Circularity is handled entirely through variable-level exclusions
(across_exclude) in get_circular_exclusions(), because the within_exclude
sets reference fine-grained category names (e.g. 'Anxiety',
'Externalizing') that do not match these broad spectrum categories.

T0 vs T2 differences:
T0 lacks : Fitbit, diet, delta variables, community dynamics,
           extended social/discrimination scales
T0 adds  : saliva biomarkers, family psych history, parent diagnostic
           composites (D_p / B_p), child mood items, sleep items,
           additional SES hardship items, additional cognitive tasks,
           parenting acceptance scales
"""

